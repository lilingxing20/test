""" 数组的转置
    二维数组a[i][j]   转置结果a[j][i] 
    三位数组a[i][j][k]   默认转置结果a[k][j][i] 
"""

import numpy as np
 
a = np.random.randint(1, 11, size=(2, 5, 3))
print(a)
# 三种转置的方法
print(a.transpose())
print(np.transpose(a))
print(a.T)

