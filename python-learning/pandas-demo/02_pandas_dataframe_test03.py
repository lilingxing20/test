""" spandas 系列（DataFrame）

DataFrame是pandas中最重要的数据结构，它可以理解为一个二维表格，每一行代表一个数据记录，每一列代表一个变量。

DataFrame的主要特点包括：
- 每列可以是不同的数据类型（如整数、浮点数、字符串等）
- 每列可以有一个名称（列索引）
- 每行可以有一个名称（行索引）
- 可以对行和列进行操作（如选择、过滤、排序等）
- 可以进行统计分析（如计算均值、标准差、相关系数等）
- 可以进行数据可视化（如绘制折线图、柱状图、散点图等）

本文将介绍pandas中DataFrame的创建、基本属性、访问、条件筛选、修改、删除等操作。

"""

import pandas as pd

data = {
    '姓名': ['张三', '李四', '王五', '赵六'],
    '年龄': [20, 21, 19, 22],
    '成绩': [90, 85, 92, 88],
    '城市': ['北京', '上海', '广州', '深圳']
}
df = pd.DataFrame(data)

print("="*50)
print("3. 访问获取DataFrame中的数据")
print("="*50)

print("原始DataFrame：")
print(df)
print()

# 选择单列（返回Series）
print("选择'姓名'列：")
print(df['姓名'])
print(type(df['姓名']))  # 查看数据类型

# 选择多列（返回DataFrame）
print("\n选择'姓名'和'成绩'列：")
print(df[['姓名', '成绩']])

# 使用loc按标签选择
print("\n选择前两行：")
print(df.loc[0:1])  # 包含结束位置

print("\n选择特定行和列：")
print(df.loc[1:2, ['姓名', '城市']])

# 使用iloc按位置选择
print("\n按位置选择前两行：")
print(df.iloc[0:2])  # 不包含结束位置

print("\n按位置选择特定行列：")
print(df.iloc[1:3, 0:2])  # 第1-2行，第0-1列
print()


