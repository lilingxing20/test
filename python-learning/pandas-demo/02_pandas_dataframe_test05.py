""" spandas 系列（DataFrame）

DataFrame是pandas中最重要的数据结构，它可以理解为一个二维表格，每一行代表一个数据记录，每一列代表一个变量。

DataFrame的主要特点包括：
- 每列可以是不同的数据类型（如整数、浮点数、字符串等）
- 每列可以有一个名称（列索引）
- 每行可以有一个名称（行索引）
- 可以对行和列进行操作（如选择、过滤、排序等）
- 可以进行统计分析（如计算均值、标准差、相关系数等）
- 可以进行数据可视化（如绘制折线图、柱状图、散点图等）

本文将介绍pandas中DataFrame的创建、基本属性、访问、条件筛选、修改、删除等操作。

"""

import pandas as pd


data = {
    '姓名': ['张三', '李四', '王五', '赵六'],
    '年龄': [20, 21, 19, 22],
    '成绩': [90, 85, 92, 88],
    '城市': ['北京', '上海', '广州', '深圳']
}

df = pd.DataFrame(data)

print("="*50)
print("5. 修改DataFrame（列操作）")
print("="*50)

# 以列的角度来进行增删改

# 1）添加新列
df['等级'] = ['A', 'B', 'A', 'B']
print("添加'等级'列后：")
print(df)

# 2）修改列
df['成绩调整'] = df['成绩'] + 5
print("\n添加'成绩调整'列后：")
print(df)

# 3）修改特定值
df.loc[0, '成绩'] = 95  # 修改张三的成绩
print("\n修改张三成绩后：")
print(df)

# 4）删除列
df_dropped = df.drop('成绩调整', axis=1)
print("\n删除'成绩调整'列后：")
print(df_dropped)
print()


