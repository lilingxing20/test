""" NumPy random函数
  - numpy.random.random(size=None)，该方法这回[0.0,1.0)范围的随机数。
  - numpy.random.randn(d0,d1.....dn)，randn函数返回一个或一组具有标准正态分布（期望为0，方差为1)的样本。dn表格每个维度，返回值为指定维度的array。
  - numpy.random.normal指定期望和方差的正态分布。正态分布(高斯分布)，参数：loc-期望；scale-方差；size-形状

NumPy的random模块提供了多种随机数生成函数，可以用于生成各种随机数。
  - random.rand()：产生均匀分布的随机数。
  - random.randn()：产生标准正态分布的随机数。
  - random.randint()：产生指定范围内的整数。
  - random.choice()：从一组元素中随机选择一个元素。

"""

import numpy as np

# 1. 产生均匀分布的随机数
print(np.random.rand(3, 2))  # 输出：[[0.5488135  0.71518937]
#  [0.60276338 0.54488318]
#  [0.4236548  0.64589411]]

# 2. 产生标准正态分布的随机数
print(np.random.randn(3, 2))  # 输出：[[ 1.62434536 -0.61175641]
#  [-0.52817175 -0.77817436]
#  [ 0.49109457  0.0964974 ]]

# 3. 指定期望和方差的正态分布
print(np.random.normal(loc=0, scale=1, size=(3, 2)))  # 输出：[[ 0.44426804 -0.22232814]
#  [-0.61175641 -0.52817175]
#  [-0.77817436  0.49109457]]

# 4. 产生指定范围内的整数
print(np.random.randint(0, 10, size=(3, 2)))  # 输出：[[5 0]
#  [2 4]
#  [8 6]]

# 5. 从一组元素中随机选择一个元素
print(np.random.choice(['a', 'b', 'c', 'd', 'e'], size=(3, 2)))  # 输出：[['a' 'b']
#  ['d' 'c']
#  ['a' 'e']]

# 6. 产生[0,1)范围的随机数
print(np.random.random(size=(3, 2)))  # 输出：[[0.5488135  0.71518937]
#  [0.60276338 0.54488318]
