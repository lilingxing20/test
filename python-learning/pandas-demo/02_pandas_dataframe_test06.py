""" spandas 系列（DataFrame）

DataFrame是pandas中最重要的数据结构，它可以理解为一个二维表格，每一行代表一个数据记录，每一列代表一个变量。

DataFrame的主要特点包括：
- 每列可以是不同的数据类型（如整数、浮点数、字符串等）
- 每列可以有一个名称（列索引）
- 每行可以有一个名称（行索引）
- 可以对行和列进行操作（如选择、过滤、排序等）
- 可以进行统计分析（如计算均值、标准差、相关系数等）
- 可以进行数据可视化（如绘制折线图、柱状图、散点图等）

本文将介绍pandas中DataFrame的创建、基本属性、访问、条件筛选、修改、删除等操作。

"""

import pandas as pd


data = {
    '姓名': ['张三', '李四', '王五', '赵六'],
    '年龄': [20, 21, 19, 22],
    '成绩': [90, 85, 92, 88],
    '城市': ['北京', '上海', '广州', '深圳']
}

df = pd.DataFrame(data)

print("="*50)
print("6. 修改DataFrame（行操作）")
print("="*50)

# 创建一个新的DataFrame用于行操作
df_row = pd.DataFrame({
    '姓名': ['张三', '李四', '王五', '赵六'],
    '年龄': [20, 21, 19, 22],
    '成绩': [90, 85, 92, 88],
    '城市': ['北京', '上海', '广州', '深圳']
})

# 1）增加新行
# 方法1：以两个dataframe的方式进行合并，使用字典创建新行
new_row = {'姓名': '王五', '年龄': 19, '成绩': 92, '城市': '广州'}
new_df = pd.DataFrame([new_row])  # 注意要放在列表中
df_new = pd.concat([df_row, new_df], ignore_index=True)
print("添加新行后：")
print(df_new)

# 添加多个新行
new_rows = pd.DataFrame([
    ['孙七', 23, 95, '杭州'],
    ['周八', 20, 87, '南京']
], columns=df_row.columns)

df_row = pd.concat([df_row, new_rows], ignore_index=True)
print("\n批量添加多行后：")
print(df_row)

# 2）删除行
# 方法1：删除单行（按索引）
df_dropped = df_row.drop(0)  # 删除索引为0的行
print("\n删除第一行后：")
print(df_dropped)

# 方法2：删除多行
df_dropped_multi = df_row.drop([1, 3])  # 删除索引为1和3的行
print("\n删除第2和第4行后：")
print(df_dropped_multi)

# 3）修改行
print("\n修改前的数据：")
print(df_row)

# 方法1：修改单行
df_row.loc[0] = ['张三丰', 25, 98, '武当山']  # 完全替换第一行
print("\n修改第一行后：")
print(df_row)

# 方法2：只修改特定列的值
df_row.loc[1, ['年龄', '成绩']] = [22, 93]  # 修改第二行的年龄和成绩
print("\n修改第二行部分值后：")
print(df_row)

# 方法3：修改单个值
df_row.loc[2, '城市'] = '成都'
print("\n修改第三行城市后：")
print(df_row)

# 方法4：按位置修改（第二行，第一列：姓名）
df_row.iloc[1, 0] = '李四四'
print("\n使用iloc修改后：")
print(df_row)

# 方法5：修改整行
df_row.iloc[2] = ['王五五', 24, 89, '重庆']
print("\n使用iloc修改整行后：")
print(df_row)
print()


